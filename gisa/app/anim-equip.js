  const along = (path, f) => {
    const L = [];
    let tot = 0;
    for (let i = 0; i + 1 < path.length; i++) {
      const l = G.vec3.len(G.vec3.sub(path[i + 1], path[i]));
      L.push(l);
      tot += l;
    }
    let d = clamp(f, 0, 1) * tot;
    let k = 0;
    while (k < L.length - 1 && d > L[k]) {
      d -= L[k];
      k++;
    }
    return G.vec3.lerp(path[k], path[k + 1], clamp(d / L[k], 0, 1));
  };

