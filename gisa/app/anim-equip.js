      g.text([0, 0, 0.62], '교번 자속 Φ', C.yellow, 0.2);
      g.hud(0.04, 0.95, 'V2 / V1 = N2 / N1 = ' + N2 * 100 + ' / 600 = ' + (N2 / 6).toFixed(2), C.white, 22);
