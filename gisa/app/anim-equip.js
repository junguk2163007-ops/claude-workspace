      g.cyl([0.15, 0, 0], [1.0, 0, 0], 0.55, [240, 200, 40], 0.4, 20);
      g.cyl([1.1, 0, 0], [2.7, 0, 0], 1.0, [30, 124, 170], 0.45, 28);
