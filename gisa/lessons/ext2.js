  P('tr-step', '과도 전류·전압 계산', '스위치를 닫고 시간이 지난 뒤의 전류나 콘덴서 전압을 묻는 문제야.', 'τ를 구하고 t/τ를 넣어서 최종값 × (1 − e^(−t/τ)).', '지수에 t만 넣거나, 감쇠 식(e^(−t/τ))을 써.');
  P('s:st-tr-switch', '투입 직후 RL', '스위치를 닫는 순간 RL 회로의 전류와 인덕터 전압을 고르는 문제야.', '투입 직후 전류 0, 인덕터 전압 V. 정상상태는 반대(전류 V/R, 전압 0).', '처음 순간과 정상상태를 바꿔.');
