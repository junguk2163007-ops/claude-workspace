// 기출에서 개념이 비어 있던 주제 보강 2차: 과도현상(RL·RC 시정수와 과도 전류·전압). 오리지널 문제, 정답은 코드로 계산
(function (G) {
  'use strict';
  const F = G.fmt;
  const n = F.num;
  const q = F.q;
  const T = G.defineTemplate;
  const S = G.defineStatic;
  const r3 = (x) => Math.round(x * 1000) / 1000;

  // ───────── 시정수 구하기 ─────────
  T({
    id: 'tr-tau',
    concept: 'transient',
    gen(r) {
      const rl = r.chance(0.5);
      let R;
      let X;
      let tau;
      if (rl) {
        R = r.pick([5, 10, 20, 25, 40, 50, 100]);
        X = r.pick([10, 20, 50, 100, 200, 500]); // 인덕턴스 mH
        tau = X / R; // mH ÷ Ω = ms
      } else {
        R = r.pick([100, 200, 500, 1000, 2000, 5000]);
        X = r.pick([1, 2, 5, 10, 20, 47, 100]); // 정전용량 μF
        tau = (R * X) / 1000; // Ω × μF = μs → ms
      }
      const dis = rl
        ? [
            { v: R / X, why: '거꾸로 나눴어. RL 회로의 시정수는 τ = L ÷ R 이야(저항으로 나누는 게 아니라 인덕턴스를 저항으로 나눠).' },
            { v: X * R, why: 'L과 R을 곱했어. RL 회로의 시정수는 곱이 아니라 τ = L ÷ R 이야(곱하는 건 RC 회로).' },
            { v: (X / R) * 1000, why: '단위를 잘못 바꿨어. mH ÷ Ω = ms 로 그대로 맞아떨어져. 1000을 곱하면 μs가 돼.' },
            { v: X / (R * 1000), why: 'mH를 H로 바꾼 뒤에 또 1000으로 나눴어. L[mH] ÷ R[Ω]이 바로 ms야.' },
            { v: X / (R * R), why: 'R을 제곱해서 나눴어. τ = L ÷ R 이야.' },
          ]
        : [
            { v: R / X, why: 'R을 C로 나눴어. RC 회로의 시정수는 곱이야: τ = R × C.' },
            { v: R * X, why: 'μF를 F로 바꾸는 걸 잊었어. R[Ω] × C[μF] = μs 라서 ms로 바꾸려면 1000으로 나눠야 해.' },
            { v: (R * X) / 1000000, why: '단위 환산을 두 번 했어. R[Ω] × C[μF] = μs, 이걸 ms로 바꾸려면 1000으로 한 번만 나눠.' },
            { v: X / R, why: 'C를 R로 나눴어. RC 회로의 시정수는 곱이야: τ = R × C.' },
          ];
      return {
        params: { mode: rl ? 'rl' : 'rc', R, X, tau },
        text: rl
          ? '저항 R = ' + q(R, 'Ω') + ', 인덕턴스 L = ' + q(X, 'mH') + '인 RL 직렬회로의 시정수는 몇 ms야?'
          : '저항 R = ' + q(R, 'Ω') + ', 정전용량 C = ' + q(X, 'μF') + '인 RC 직렬회로의 시정수는 몇 ms야?',
        formula: rl ? 'τ = L / R' : 'τ = R × C',
        unit: 'ms',
        decimals: 3,
        answer: tau,
        distractors: dis,
        conclusion: rl ? 'τ = L ÷ R = ' + n(X) + ' mH ÷ ' + n(R) + ' Ω = ' + q(tau, 'ms', 3) : 'τ = R × C = ' + n(R) + ' Ω × ' + n(X) + ' μF = ' + n(R * X) + ' μs = ' + q(tau, 'ms', 3),
        steps: rl
          ? ['RL 직렬회로의 시정수는 τ = L ÷ R 이야.', 'mH ÷ Ω 은 그대로 ms 단위야.', n(X) + ' ÷ ' + n(R) + ' = ' + q(tau, 'ms', 3) + '.']
          : ['RC 직렬회로의 시정수는 τ = R × C 이야.', 'Ω × μF = μs 이니까 ms로 바꾸려면 1000으로 나눠.', n(R) + ' × ' + n(X) + ' = ' + n(R * X) + ' μs = ' + q(tau, 'ms', 3) + '.'],
        check: rl ? n(tau, 3) + ' ms × ' + n(R) + ' Ω = ' + n(X) + ' mH (L = τ × R)' : n(tau, 3) + ' ms ÷ ' + n(R) + ' Ω = ' + n(X / 1000, 4) + ' mF = ' + n(X) + ' μF',
        traps: ['RL은 L ÷ R, RC는 R × C로 서로 달라.', '단위를 먼저 맞춰: mH는 10⁻³ H, μF는 10⁻⁶ F.'],
      };
    },
  });

  // ───────── 과도 전류·전압 ─────────
  T({
    id: 'tr-step',
    concept: 'transient',
    gen(r) {
      const rl = r.chance(0.5);
      const V = r.pick([10, 12, 24, 50, 100, 110, 200]);
      const nn = r.pick([0.5, 1, 2, 3]);
      let R;
      let tau;
      let X;
      if (rl) {
        R = r.pick([10, 20, 50, 100]);
        tau = r.pick([1, 2, 5, 10, 20]);
        X = tau * R; // 인덕턴스 mH
      } else {
        R = r.pick([100, 200, 500, 1000]);
        tau = r.pick([1, 2, 5, 10, 20]);
        X = (tau * 1000) / R; // 정전용량 μF
      }
      const t = nn * tau;
      const fin = rl ? V / R : V;
      const frac = 1 - Math.exp(-nn);
      const ans = r3(fin * frac);
      const unit = rl ? 'A' : 'V';
      const lab = (v) => q(v, unit, 3);
      const dis = [
        { v: r3(fin), why: '정상상태 값(최종값)이야. 시간이 t = ' + n(t) + ' ms 일 때는 아직 최종값에 다 못 갔어. 최종값 × (1 − e^(−t/τ))를 써야 해.' },
        { v: r3(fin * Math.exp(-nn)), why: '충전(증가)이 아니라 감쇠 식 e^(−t/τ)를 썼어. 스위치를 닫으면 0에서 올라가니까 1 − e^(−t/τ)를 곱해야 해.' },
        { v: r3(fin * (1 - Math.exp(-1))), why: '63.2 %는 t = τ(' + n(tau) + ' ms) 일 때의 비율이야. 이 문제는 t = ' + n(t) + ' ms = ' + n(nn) + 'τ 라서 1 − e^(−' + n(nn) + ')을 써야 해.' },
        { v: r3(fin * Math.min(1, nn) * 0.5), why: '시간에 비례해서 직선으로 올라가는 게 아니야. 지수 곡선이라서 1 − e^(−t/τ)로 계산해.' },
        { v: r3(fin * (1 - Math.exp(-t))), why: 't를 시정수로 나누지 않고 ms 값을 그대로 지수에 넣었어. 지수에는 t/τ = ' + n(nn) + ' 를 넣어야 해.' },
      ];
      return {
        params: { mode: rl ? 'rl' : 'rc', V, R, X, tau, t, nn },
        text: rl
          ? '저항 ' + q(R, 'Ω') + '과 인덕턴스 ' + q(X, 'mH') + '가 직렬인 RL 회로에 직류 ' + q(V, 'V') + '를 스위치로 연결했어. 스위치를 닫고 ' + q(t, 'ms') + ' 뒤의 전류는 몇 A야?'
          : '저항 ' + q(R, 'Ω') + '과 정전용량 ' + q(X, 'μF') + '(처음에 충전 안 됨)가 직렬인 RC 회로에 직류 ' + q(V, 'V') + '를 스위치로 연결했어. 스위치를 닫고 ' + q(t, 'ms') + ' 뒤의 콘덴서 전압은 몇 V야?',
        formula: rl ? 'τ = L/R,   i(t) = (V/R)(1 − e^(−t/τ))' : 'τ = R·C,   v_c(t) = V(1 − e^(−t/τ))',
        unit,
        decimals: 3,
        answer: ans,
        distractors: dis,
        conclusion: 'τ = ' + n(tau) + ' ms, t/τ = ' + n(nn) + ' → ' + (rl ? 'i' : 'v_c') + ' = ' + n(fin) + ' × (1 − e^(−' + n(nn) + ')) = ' + lab(ans),
        steps: [
          '시정수부터 구해: ' + (rl ? 'τ = L ÷ R = ' + n(X) + ' mH ÷ ' + n(R) + ' Ω = ' + n(tau) + ' ms' : 'τ = R × C = ' + n(R) + ' Ω × ' + n(X) + ' μF = ' + n(tau) + ' ms') + '.',
          't/τ = ' + n(t) + ' ÷ ' + n(tau) + ' = ' + n(nn) + '.',
          (rl ? '최종 전류 V/R = ' + n(fin) + ' A' : '최종 전압 = 전원 전압 ' + n(fin) + ' V') + ' 이고, 처음 0에서 올라가니까 곱할 비율은 1 − e^(−' + n(nn) + ') = ' + n(frac, 4) + '.',
          n(fin) + ' × ' + n(frac, 4) + ' = ' + lab(ans) + '.',
        ],
        check: '비율 ' + n(frac, 3) + '는 0과 1 사이이고, ' + (nn === 1 ? 't = τ 일 때 63.2 %' : nn < 1 ? 't < τ 라서 63.2 %보다 작아' : 't > τ 라서 63.2 %보다 커') + '. 최종값 ' + n(fin) + ' ' + unit + '보다 작은 값이야.',
        traps: ['지수에는 t를 시정수로 나눈 값(t/τ)을 넣어.', '스위치를 닫는 순간 RL의 전류, RC의 콘덴서 전압은 0이고 그다음에 최종값을 향해 올라가.'],
      };
    },
  });

  // ───────── 이론형 ─────────
  S({
    id: 'st-tr-switch',
    concepts: ['transient'],
    text: 'RL 직렬회로에 직류 전압 V를 스위치로 연결하는 순간(스위치를 닫은 직후)의 전류와 인덕터 단자전압은? (인덕터에 처음 전류는 0)',
    choices: [
      { label: '전류 0, 인덕터 전압 V', why: '정답이야. 코일은 전류가 갑자기 변하는 걸 막아서 순간 전류는 0이고, 저항 전압도 0이라서 전원 전압 V가 전부 인덕터에 걸려.' },
      { label: '전류 V/R, 인덕터 전압 0', why: '이건 시간이 한참 지난 정상상태야. 정상상태에서는 코일이 단순한 도선이라 전압이 0이고 전류가 V/R이야.' },
      { label: '전류 0, 인덕터 전압 0', why: '전류가 0이면 저항에 걸리는 전압도 0이라서, 전원 전압 V가 어딘가에는 걸려야 해. 그게 인덕터야.' },
      { label: '전류 V/R, 인덕터 전압 V', why: '전류가 V/R이면 저항에 전압 V가 걸리니까 인덕터에 또 V가 걸릴 수 없어. 합이 전원 전압을 넘어.' },
    ],
    answer: 0,
    formula: '스위치 투입 직후: i(0) = 0, v_L(0) = V.  정상상태: i = V/R, v_L = 0',
    conclusion: '투입 직후 RL 회로는 전류 0, 인덕터 전압 V야.',
    steps: ['인덕터 전류는 순간적으로 변할 수 없어서 투입 직후 i = 0.', '전류가 0이니까 저항 전압은 R × 0 = 0.', '전원 전압 V = 저항 전압 + 인덕터 전압이라서 인덕터 전압이 V.'],
    check: '시간이 지나면 전류가 V/R로 올라가고 인덕터 전압은 0으로 줄어들어(둘이 정반대로 움직여).',
    traps: ['"처음 순간"과 "정상상태"는 정반대야. 코일은 처음엔 끊어진 것처럼, 나중엔 도선처럼 행동해.'],
  });

  S({
    id: 'st-tr-rc',
    concepts: ['transient'],
    text: 'RC 직렬회로를 직류 전원 V에 연결하고 시간이 충분히 지난 뒤(정상상태)의 콘덴서 전압과 회로 전류는?',
    choices: [
      { label: '콘덴서 전압 V, 전류 0', why: '정답이야. 충전이 끝나면 콘덴서는 전원 전압까지 차서 더 이상 전류가 흐르지 않아(콘덴서는 직류에서 끊어진 것처럼 행동).' },
      { label: '콘덴서 전압 0, 전류 V/R', why: '이건 스위치를 닫은 직후의 모습이야. 처음엔 콘덴서가 단락된 것처럼 전압 0, 전류 V/R이야.' },
      { label: '콘덴서 전압 V/2, 전류 V/(2R)', why: '절반이 되는 건 정상상태가 아니야. 충전이 끝나면 전압은 V, 전류는 0이 돼.' },
      { label: '콘덴서 전압 V, 전류 V/R', why: '콘덴서 전압이 V까지 차면 저항에 걸리는 전압이 0이라서 전류도 0이야.' },
    ],
    answer: 0,
    formula: '충전 직후: v_c = 0, i = V/R.  정상상태: v_c = V, i = 0',
    conclusion: '정상상태의 RC 회로는 콘덴서 전압 V, 전류 0이야.',
    steps: ['시간이 충분히 지나면 콘덴서가 전원 전압 V까지 충전돼.', '저항 전압 = 전원 전압 − 콘덴서 전압 = 0 이라서 전류도 0.', '그래서 직류 정상상태에서 콘덴서는 개방(끊어진 것)으로 볼 수 있어.'],
    check: '5τ 정도가 지나면 이 상태에 거의 도달해(99 % 이상).',
    traps: ['RL(코일)은 정상상태에서 단락(도선), RC(콘덴서)는 정상상태에서 개방(끊김)이야.'],
  });
})(globalThis.GISA);
